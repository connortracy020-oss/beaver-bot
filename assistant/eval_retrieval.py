"""Retrieval benchmark: how often an expected source appears in the top 3 and top 5 results.

    python -m assistant.eval_retrieval                  # all questions in eval/questions.csv
    python -m assistant.eval_retrieval --origin real    # only the survey questions, once they're added

Writes docs/retrieval-eval.md. Questions marked should_refuse=yes aren't scored for hits; for those the report
shows how strong the best match was, which is what the refusal threshold is tuned against.
"""
import argparse
import csv
import sys
from collections import defaultdict
from statistics import median

from osu_crawl.config import ROOT

from .answer import CRISIS_RE, WEAK_COVERAGE, guard
from .retrieve import connect, search

QUESTIONS = ROOT / "eval" / "questions.csv"


def norm(url: str) -> str:
    return url.strip().split("#")[0].rstrip("/")


def load(path=QUESTIONS, origin: str | None = None) -> list[dict]:
    with open(path, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    for r in rows:
        r["expected"] = [norm(u) for u in r["expected_source_urls"].split("|") if u.strip()]
        r["refuse"] = r["should_refuse"].strip().lower() == "yes"
    return [r for r in rows if origin is None or r.get("origin", "").strip() == origin]


def first_hit_rank(hits, expected) -> int | None:
    for i, h in enumerate(hits, 1):
        if norm(h.page_url) in expected:
            return i
    return None


def run(rows: list[dict], k: int = 5) -> dict:
    con = connect()
    scored, refusals = [], []
    for r in rows:
        hits = search(con, r["question"], k)
        top = hits[0] if hits else None
        rec = {**r, "hits": hits, "rank": first_hit_rank(hits, r["expected"]),
               "top_score": top.score if top else 0.0, "top_coverage": top.coverage if top else 0.0}
        (refusals if r["refuse"] else scored).append(rec)
    return {"scored": scored, "refusals": refusals}


def pct(n, d):
    return f"{n}/{d} ({100 * n / d:.0f}%)" if d else "n/a"


def report(res: dict, label: str) -> str:
    scored, refusals = res["scored"], res["refusals"]
    at3 = sum(1 for r in scored if r["rank"] and r["rank"] <= 3)
    at5 = sum(1 for r in scored if r["rank"] and r["rank"] <= 5)
    lines = [f"# Retrieval eval ({label})", "",
             "Generated by `python -m assistant.eval_retrieval`. Keyword search only (SQLite FTS5, BM25); no "
             "embeddings and no model calls.", "",
             f"- **Questions scored:** {len(scored)} answerable, from `eval/questions.csv`.",
             f"- **Not scored:** {len(refusals)} questions the app should decline.",
             "- **A hit:** any expected source page in the top k results.", "",
             "| | Top 3 | Top 5 |", "|---|---|---|",
             f"| All answerable questions | {pct(at3, len(scored))} | {pct(at5, len(scored))} |"]
    by_cat = defaultdict(list)
    for r in scored:
        by_cat[r["category"]].append(r)
    for cat, rs in sorted(by_cat.items()):
        c3 = sum(1 for r in rs if r["rank"] and r["rank"] <= 3)
        c5 = sum(1 for r in rs if r["rank"] and r["rank"] <= 5)
        lines.append(f"| {cat} | {pct(c3, len(rs))} | {pct(c5, len(rs))} |")
    lines += ["", "## Every answerable question", "",
              "| Question | Category | Rank of first expected source | Top result |", "|---|---|---:|---|"]
    for r in scored:
        top = r["hits"][0] if r["hits"] else None
        top_txt = f"[{top.title}]({top.url})" if top else "(none)"
        lines.append(f"| {r['question']} | {r['category']} | {r['rank'] or 'miss'} | {top_txt} |")
    misses = [r for r in scored if not r["rank"] or r["rank"] > 3]
    if misses:
        lines += ["", "## Not in the top 3", ""]
        for r in misses:
            lines += [f"**{r['question']}**", "", f"- **Expected:** {', '.join(r['expected'])}", "- **Got:**"]
            lines += [f"  {i}. {h.title}: {h.heading_path} ({h.page_url})" for i, h in enumerate(r["hits"], 1)]
            lines.append("")
    lines += ["## How the ranking settings were chosen", "",
              "Run on 2026-10-26 against the 25 answerable synthetic questions (top 1 / top 3 / top 5):", "",
              "| Setting | Top 1 | Top 3 | Top 5 |", "|---|---:|---:|---:|",
              "| Plain BM25 (title/headings weighted 3x) | 10 | 17 | 19 |",
              "| + prefix matching as crude stemming (\"counse*\") | 9 | 16 | 17 |",
              "| + exact word-pair boosts (\"payment plan\") | 10 | 15 | 17 |",
              "| + link authority 0.15 (pages many OSU sites link to) | 12 | 20 | 21 |",
              "| + PDFs weighted 0.8 | 12 | 17 | 19 |",
              "| **Authority 0.15 + PDFs 0.8 (current)** | **13** | **20** | **21** |",
              "| Authority 0.25 + PDFs 0.8 | 12 | 20 | 22 |", "",
              "Authority between 0.1 and 0.25 gives the same top-3 score, so the setting isn't fragile. With only 25 "
              "questions, one question is 4 points: treat these as rough.", "",
              "**Two expected-source lists were corrected after this table** (2026-10-26). Both pages answer the "
              "question directly but were missed when the questions were written: Student Accounts' *Payment Plans* "
              "page, and UHDS's *About the Housing Application* (\"There is a live-on requirement for first-year "
              "students\"). The correction moved top 5 from 21 to 22; top 3 stayed at 20.", ""]
    lines += _refusal_section(scored, refusals)
    ans_cov = [r["top_coverage"] for r in scored]
    lines += ["## Strength of the best match", "",
              "`coverage` is the share of the question's search words found in the top chunk. The answer layer "
              "uses it to decide when retrieval is too weak to answer.", "",
              f"- **Answerable questions:** median top coverage {median(ans_cov):.2f}, minimum {min(ans_cov):.2f}."
              if ans_cov else "", "",
              "| Should decline | Top coverage | Top result |", "|---|---:|---|"]
    for r in refusals:
        top = r["hits"][0] if r["hits"] else None
        lines.append(f"| {r['question']} | {r['top_coverage']:.2f} | {top.title if top else '(none)'} |")
    lines.append("")
    return "\n".join(lines)


def _declined_before_model(r) -> str:
    """Why the answer layer declines this question before any model runs, or "" if it doesn't."""
    if CRISIS_RE.search(r["question"]):
        return "crisis resources"
    g = guard(r["question"])
    if g:
        return g.reason
    return "weak retrieval" if not r["hits"] or r["top_coverage"] < WEAK_COVERAGE else ""


def _refusal_section(scored, refusals) -> list[str]:
    caught = [(r, _declined_before_model(r)) for r in refusals]
    wrong = [(r, why) for r in scored if (why := _declined_before_model(r))]
    lines = ["## Declining before any model runs", "",
             "The answer layer declines some questions on its own (answer.py: crisis, guard, weak retrieval). "
             "Anything it lets through still needs the model to answer from the excerpts, and the verifier to "
             "accept the quotes.", "",
             f"- **Should decline:** {sum(1 for _, w in caught if w)} of {len(caught)} declined before the model.",
             f"- **Answerable but declined:** {len(wrong)} of {len(scored)}.", "",
             "| Should decline | Declined before the model? |", "|---|---|"]
    lines += [f"| {r['question']} | {w or 'no: left to the model and the verifier'} |" for r, w in caught]
    lines += [f"| (answerable) {r['question']} | wrongly declined: {w} |" for r, w in wrong]
    return lines + [""]


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--origin", choices=["synthetic", "real"], help="only questions of this origin")
    ap.add_argument("--out", default=str(ROOT / "docs" / "retrieval-eval.md"))
    args = ap.parse_args(argv)
    rows = load(origin=args.origin)
    res = run(rows)
    text = report(res, args.origin or "all questions")
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(text)
    scored = res["scored"]
    at3 = sum(1 for r in scored if r["rank"] and r["rank"] <= 3)
    at5 = sum(1 for r in scored if r["rank"] and r["rank"] <= 5)
    print(f"top-3: {pct(at3, len(scored))}   top-5: {pct(at5, len(scored))}   -> {args.out}")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
